create table if not exists rate
(
    id                       bigint  default nextval('rate_id_seq'::regclass) not null
        primary key,
    edu_cess                 numeric(19, 2),
    from_date                date,
    net_rate_with_sc         numeric(19, 2),
    net_rate_without_sc      numeric(19, 2),
    notes                    varchar(255),
    round_off                integer                                          not null,
    surcharge                numeric(19, 2),
    tds                      numeric(19, 2),
    tds_code                 varchar(255),
    tds_sub_code             varchar(255),
    ds_code varchar(255),
    deductee_status_fk       bigint
        constraint fk_rate_deducteestatus
            references deductee_status,
    version                  integer default 0                                not null,
    created_at               timestamp,
    created_by               bigint,
    modified_at              timestamp,
    modified_by              bigint,
    threshold_amt            numeric(19, 4),
    threshold_limit_override boolean default false,
    constraint uk_rate
        unique (tds_code, tds_sub_code, deductee_status_fk, from_date)
);

