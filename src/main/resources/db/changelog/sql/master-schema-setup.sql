create table if not exists audit_log
(
    id              serial
        primary key,
    schema_name     text,
    table_name      text,
    record_id       bigint,
    operation_type  text,
    changed_at      timestamp default now(),
    changed_by      bigint,
    original_values jsonb,
    new_values      jsonb
);

create table if not exists deductee_category
(
    id    bigint not null
        constraint pk_deductee_category
            primary key,
    label varchar(255)
);

create table if not exists deductee_status
(
    id                  bigint generated by default as identity
        constraint pk_deducteestatus
            primary key,
    code                varchar(255),
    deductee_type       integer,
    description         varchar(500),
    remarks             varchar(500),
    surcharge_mandatory boolean,
    surcharge_threshold double precision
);

