create table if not exists user_detail
(
    id                     bigint  default nextval('user_id_seq'::regclass) not null
        primary key,
    company                varchar(255),
    email                  varchar(255)                                     not null
        constraint uk_user_detail_email
            unique,
    failure_login_attempts integer,
    is_admin               boolean default false                            not null,
    last_logged_in_time    timestamp,
    locked                 boolean,
    name                   varchar(255)                                     not null,
    password               varchar(255)                                     not null,
    token_count            integer,
    temporary_password     boolean default false                            not null
);

create table if not exists workspace
(
    id             bigint default nextval('workspace_id_seq'::regclass) not null
        primary key,
    financial_year varchar(255),
    form_no        varchar(255),
    name           varchar(255),
    type           varchar(20)
        constraint check_types
            check ((type)::text = ANY
                   (ARRAY [('WK_TDSPAC'::character varying)::text, ('WK_34AB'::character varying)::text, ('WK_26AS'::character varying)::text])),
    properties     jsonb
);

create table if not exists api_key
(
    id           integer default nextval('api_key_id_seq'::regclass) not null
        constraint pk_api_key
            primary key,
    version      integer                                             not null,
    created_at   timestamp,
    created_by   bigint,
    modified_at  timestamp,
    modified_by  bigint,
    key          varchar(500)                                        not null,
    name         varchar(255),
    workspace_fk bigint
        constraint fk_api_key_on_workspace_fk
            references workspace
);

create table if not exists certificate
(
    id                 bigint default nextval('certificate_seq'::regclass) not null
        primary key,
    amount             numeric(19, 2),
    certificate_number varchar(255),
    certificate_type   varchar(255),
    from_date          date,
    pan                varchar(255),
    rate               numeric(19, 2),
    request_number     varchar(255),
    section            varchar(255),
    to_date            date,
    financial_year     varchar(255),
    workspace_fk       bigint
        constraint fk_certificate_workspace
            references workspace,
    utilized           numeric(19, 2),
    name               varchar(255),
    sub_section        varchar(255)
);

