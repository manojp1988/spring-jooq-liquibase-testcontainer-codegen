create table if not exists transaction_audit
(
    id            bigint default nextval('transaction_audit_id_seq'::regclass) not null
        constraint pk_transaction_audit
            primary key,
    workspace_fk  bigint
        constraint fk_transactionaudit_on_workspace_fk
            references workspace,
    uploaded_date timestamp,
    status        boolean                                                      not null,
    upload_id     bigint,
    remarks       varchar(255),
    user_fk       bigint
        constraint fk_transaction_audit_user
            references user_detail
