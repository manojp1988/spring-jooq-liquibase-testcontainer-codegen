create table if not exists workspace_users
(
    user_fk      bigint                                                               not null
        constraint fk_woruse_on_user
            references user_detail,
    workspace_fk bigint                                                               not null
        constraint fk_woruse_on_workspace
            references workspace
            on delete cascade,
    is_active    boolean   default false,
    last_used_at timestamp default '1970-01-01 00:00:00'::timestamp without time zone not null,
    constraint pk_workspace_users
        primary key (user_fk, workspace_fk)
);
